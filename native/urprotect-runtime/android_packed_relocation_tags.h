#define URP_DT_ANDROID_RELRCOUNT UINT64_C(0x6fffe005)
#define URP_DT_ANDROID_RELRSZ UINT64_C(0x6fffe001)
#define URP_DT_ANDROID_RELRENT UINT64_C(0x6fffe003)

#endif
